function readJSON(f) {
  let raw;
  try { raw = fs.readFileSync(f, 'utf8'); } catch (e) { die('cannot read ' + path.relative(ROOT, f) + ': ' + e.message); }
  try { return JSON.parse(raw); } catch (e) { die('malformed JSON in ' + path.relative(ROOT, f) + ': ' + e.message); }
}

