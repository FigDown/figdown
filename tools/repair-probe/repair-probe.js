// `supportsDiagnostics` records whether the CURRENT engine build's `errors`
// channel comes with the structured `diagnostics` envelope alongside it —
// checked, not assumed, on the same capability probe that decides which
// error channel to use. After the envelope's retraction (§9,
// decisions/registry.md) this is `false` against every dist build
// in the tree, permanently, by design: the envelope is gone from the engine
// surface on purpose, not as a build that has yet to catch up. `--check` and
// condition `A` do not need it (they read `errors`, never `diagnostics`);
// condition `B` cannot honestly run without it — see `runCondition`'s guard
// below, which is the one behavioural change retraction required of this
// harness.
function loadValidator() {
  const distMod = requireDistFresh();
  const primary = {
    parse: (text) => distMod.parse(text),
    render: (text) => distMod.render(text, {}),
  };
  const probe = primary.render(CAPABILITY_PROBE_FD);
  if (probe.errors && probe.errors.length) {
    return Object.assign({ channel: 'dist-public-api', supportsDiagnostics: !!(probe.diagnostics && probe.diagnostics.length) }, primary);
  }
  const fallback = loadEngineFallback();
  if (fallback) {
    const fprobe = fallback.render(CAPABILITY_PROBE_FD);
    if (fprobe.errors && fprobe.errors.length) {
      return Object.assign({ channel: 'engine-direct-fallback (dist public render() did not surface geometry errors at probe time)', supportsDiagnostics: false }, fallback);
    }
  }
  die('neither dist\'s public render() nor the in-memory engine fallback surfaces geometry errors on the capability probe — cannot validate geometry fixtures');
}

// ── validating an arbitrary document against a fixture's invariants ────────
function validateDocument(validator, text, invariants) {
  const r = validator.render(text);
  const errors = r.errors || [];
  const diagnostics = r.diagnostics || [];
  const p = validator.parse(text);
  const doc = p.doc || null;
  let nodeIds = [], edgeCount = null, missing = invariants.must_have_nodes.slice(), invariantsPass = false;
  if (doc) {
    nodeIds = (doc.nodes || []).map((n) => n.id);
    edgeCount = (doc.edges || []).length;
    missing = invariants.must_have_nodes.filter((id) => !nodeIds.includes(id));
    invariantsPass = missing.length === 0 && edgeCount >= invariants.min_edges;
  }
  return {
    errors, diagnostics, doc,
    nodeCount: nodeIds.length, edgeCount, missingNodes: missing,
    invariantsPass,
    success: errors.length === 0 && invariantsPass,
  };
}

// ── mode: --check (offline, pure function of the tree) ──────────────────────
// Checks the ERROR COUNT and, when the loaded engine build supports it, the
// exact `diagnostics[].code` MULTISET against a fixture's recorded
// `immediate_codes`/`latent_codes`. After the envelope's retraction (§9,
// decisions/registry.md) `validator.supportsDiagnostics` is
// permanently false and every fixture's `diagnostics` array is `[]` — this
// is EXPECTED, not a fixture defect, so the code check degrades to "codes
// unavailable, verified by error count only" instead of failing. What never
// degrades is the count and the CLASS of message text (still printed,
// still readable by eye against `f.klass`): retraction removed the
// structured channel, not the plain-string one `--check`'s count check and
// condition `A` both actually depend on.
function runCheck() {
  const validator = loadValidator();
  console.log('CHECK — engine channel: ' + validator.channel + (validator.supportsDiagnostics ? '' : '  [no diagnostics envelope on this build — codes checked by count only, see design/repair-probe-baseline.md §9]'));
  let bad = false;
  for (const f of FIXTURES) {
    const inv = readInvariants(f.id);
    const broken = validateDocument(validator, readFixtureText(f.id), inv);
    const repaired = validateDocument(validator, readRepairedText(f.id), inv);
    const cheat = validateDocument(validator, readCheatText(f.id), inv);

    const brokenCodes = broken.diagnostics.map((d) => d.code);
    const brokenOk = validator.supportsDiagnostics
      ? broken.errors.length === f.immediate_codes.length && sameCodeMultiset(brokenCodes, f.immediate_codes)
      : broken.errors.length === f.immediate_codes.length;
    const repairedOk = repaired.success;
    const cheatCaught = cheat.errors.length === 0 && !cheat.invariantsPass; // reaches zero errors, invariants still refuse it

    console.log('  ' + f.id + ' [' + f.set + '] [' + f.klass + ']');
    console.log('    broken:   ' + broken.errors.length + ' error(s)' + (validator.supportsDiagnostics ? ', codes=' + JSON.stringify(brokenCodes) : ' (codes unavailable — wanted ' + JSON.stringify(f.immediate_codes) + ' by count)') + (brokenOk ? '  OK' : '  FAIL (wanted ' + JSON.stringify(f.immediate_codes) + ')'));
    if (!brokenOk) broken.errors.forEach((e) => console.log('      ' + e));

    let latentOk = true;
    if (f.latent_codes.length) {
      const stage1 = validateDocument(validator, readStage1Text(f), inv);
      const stage1Codes = stage1.diagnostics.map((d) => d.code);
      latentOk = validator.supportsDiagnostics
        ? stage1.errors.length === f.latent_codes.length && sameCodeMultiset(stage1Codes, f.latent_codes)
        : stage1.errors.length === f.latent_codes.length;
      console.log('    stage1:   (' + f.stage1_suffix + ', parse defect fixed, nothing else) ' + stage1.errors.length + ' error(s)' + (validator.supportsDiagnostics ? ', codes=' + JSON.stringify(stage1Codes) : ' (codes unavailable — wanted ' + JSON.stringify(f.latent_codes) + ' by count)') + (latentOk ? '  OK — latent error(s) surface exactly as recorded' : '  FAIL (wanted ' + JSON.stringify(f.latent_codes) + ')'));
      if (!latentOk) stage1.errors.forEach((e) => console.log('      ' + e));
    }

    console.log('    repaired: ' + (repairedOk ? 'validates clean, invariants hold  OK' : 'FAIL — errors=' + JSON.stringify(repaired.errors) + ' missing=' + JSON.stringify(repaired.missingNodes) + ' edges=' + repaired.edgeCount + '/' + inv.min_edges));
    console.log('    cheat:    ' + (cheatCaught ? 'reaches zero errors but invariants correctly refuse it (missing=' + JSON.stringify(cheat.missingNodes) + ', edges=' + cheat.edgeCount + '/' + inv.min_edges + ')  OK' : 'FAIL — anti-cheat did not catch the lazy-deletion variant'));

    if (!brokenOk || !latentOk || !repairedOk || !cheatCaught) bad = true;
  }
  console.log('');
  console.log(bad
    ? 'CHECK: FAIL'
    : 'CHECK: all ' + FIXTURES.length + ' fixtures (' + RUN1_FIXTURE_IDS.length + ' run1 + ' + FLOOR_FIXTURE_IDS.length + ' floor) produce their intended error set, staged latent errors surface exactly where recorded, all repairs validate clean, all cheats are caught by the invariants.'
      + (validator.supportsDiagnostics ? '' : ' (diagnostics envelope retracted from this engine build — verified by error count, not code — see §9.)'));
  return !bad;
}

// ── extraction: the last fenced code block in a reply ───────────────────────
function extractDocument(text) {
  const re = /```[^\n]*\n([\s\S]*?)```/g;
  let m, last = null;
  while ((m = re.exec(String(text || ''))) !== null) last = m[1];
  return last === null ? null : last.replace(/\s+$/, '') + '\n';
}

// ── email scrub at capture time (decisions/registry.md item 50) ─────────
const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;
function scrubEmails(text) {
  let n = 0;
  const out = String(text || '').replace(EMAIL_RE, () => { n++; return '<redacted-email>'; });
  return { text: out, replacements: n };
}

