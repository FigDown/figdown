#!/usr/bin/env node
// repair-probe.js — THE COLD-REPAIR A/B GATE.
//
// WHAT IT MEASURES
// ----------------
// A structured diagnostics envelope was added to the engine's public API
// (dist's `parse()`/`render()` now return a `diagnostics` array alongside the
// plain-string `errors` array — spec core §8.4: one entry per error string,
// carrying a `code`, a `subject`, `evidence`, and engine-verified
// `supportedFixes`). Whether that envelope is worth putting in front of an
// authoring agent — worth documenting, worth teaching, worth shipping as part
// of the library surface — is a question with a measurable answer: does a
// COLD agent repair a broken `.fd` faster and more reliably when it is shown
// the envelope, compared with being shown only the plain error strings the
// engine has always produced?
//
//   condition A (control)   the validator's plain error strings, verbatim.
//                            This is what every caller has always had.
//   condition B (treatment) the same error strings PLUS the diagnostics
//                            envelope, pretty-printed JSON, for the SAME
//                            errors. This is the proposal.
//
// The decision this buys is stated, in full, and FROZEN BEFORE THE RUN, in
// decisions/registry.md — copy it there, not here, so it cannot
// drift between the tool and its own record. In short: B only enters the
// library surface if it clears a stated bar over A on first-round success
// rate or mean rounds-to-success; otherwise the envelope is retracted or
// redesigned, and the result is recorded either way.
//
// THE COLD ROOM
// -------------
// Identical in kind to tools/genre-probe/genre-probe.js's (itself identical
// to decisions/registry.md's): an isolated empty temporary
// directory outside the repository, every tool denied BY NAME, no MCP
// servers, no settings/memory/skills/plugins/hooks, no session persistence.
// Unlike the genre probe, a repair chain can take up to THREE rounds — but
// each round is its own COLD, STATELESS call. Round 2 does not continue a
// conversation with round 1; it is a fresh `claude` invocation that is shown
// the reader's OWN document from the end of the previous round, plus a fresh
// validator run against it. No transcript, no memory, no session ID crosses
// a round boundary. This is what makes every round individually reproducible
// from the files in this tree.
//
// THE LESSON THIS TOOL WAS BUILT AROUND (decisions/registry.md item 50)
// --------------------------------------------------------------------------
// The comprehension suite's cold room leaked the running account's email
// address into every reader's own invented provenance line, because readers
// were asked to emit a document's opening lines with no provenance line to
// copy, and the model filled the gap from wherever the harness supplied it.
// Two independent defenses are taken here, not one:
//   (a) the reader is instructed to emit ONLY the corrected document in one
//       fenced code block — no provenance comment, no commentary outside the
//       fence — which removes the invitation that produced the leak;
//   (b) `raw_answer_text` is scrubbed for an email pattern AT CAPTURE TIME
//       regardless, and every transcript records that the scrub ran and how
//       many replacements it made (0 expected, given (a)).
//
// THE ENGINE, READ ONLY
// ----------------------
// This tool calls `dist/figdown.js`'s public API and never edits it. As of
// this probe's authoring, that dist build's `render()` already threads the
// geometry channel and the `diagnostics` envelope all the way through (see
// the comment above `render()` in dist/figdown.js, "Until 0.4 this
// wrapper discarded that channel..."). Because dist is regenerated by a
// concurrent process, `--check` and `--run` re-probe the CURRENT dist build's
// capability every time they start (`loadValidator()` below) rather than
// assuming it: if a future dist build ever regresses render()'s error
// channel, this tool falls back to a read-only, IN-MEMORY patch of the
// loaded module text that exposes the engine's internal `render()` result
// directly — dist/figdown.js on disk is never written to. Every transcript
// and every --check report records which channel answered the validation
// question, so a channel regression is visible in the data rather than
// silently changing what was measured.
//
// USAGE
//   node tools/repair-probe/repair-probe.js --check                        offline: fixtures still
//                                                                            produce their intended
//                                                                            errors, repairs still
//                                                                            validate, cheats still
//                                                                            get caught (pure function)
//   node tools/repair-probe/repair-probe.js --run --condition A            live: 8 fixtures × 3 seats
//   node tools/repair-probe/repair-probe.js --run --condition B            live: 8 fixtures × 3 seats
//   node tools/repair-probe/repair-probe.js --run --condition A --fixture G1,G3   live: one condition,
//                                                                            named fixtures only
//   node tools/repair-probe/repair-probe.js --write-results                offline rescoring from
//                                                                            the stored transcripts
//   node tools/repair-probe/repair-probe.js --verify                       fixture files still match
//                                                                            what each transcript recorded
//   node tools/repair-probe/repair-probe.js --report                       the results, as text
//
// `--run` is the only mode that calls a model. Everything else is a pure
// function of files in this tree. Exit codes: 0 clean · 1 a finding ·
// 2 tool error.
